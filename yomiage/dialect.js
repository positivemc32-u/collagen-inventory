// =============================================================
// dialect.js … 標準語の文章を、読み上げのときだけ関西弁の言い回しにする
// 画面の文章はそのままです。イントネーション（アクセント）は端末の声のままです。
// 「読んだ」（過去）と「行くんだ」（〜のだ）のような、まちがえやすい所は変えないようにしています。
// =============================================================
'use strict';

const Dialect = (() => {
  // 文の終わり（この後ろに続くのが句読点・かっこ・空白・文末）
  const END = '(?=[。、！？!?…\\s」』）)]|$)';
  // 「だ」の前に来てよい言葉（漢字・カタカナ、またはよく使う名詞）
  const NOUN = '(?<=[一-龯々ァ-ヶー]|これ|それ|あれ|どれ|ここ|そこ|もの|こと|ため|とき|はず|よう|みたい|まま|だけ|ばかり|ほど|くらい|ぐらい|ほんま|なに|れい|嫌い|[^ぁ-ん][かき])';
  // 「〜んだ」が「〜のだ」の意味になる形（行くんだ・したんだ・好きなんだ）
  const EXPL = '(?<=[うくすつぬふむゆるぐずづぶぷいたな])';
  // 文のはじめ
  const START = '(?<=^|[。！？!?\\n」』]\\s*)';
  // 否定の「ない」の後ろ（「ないで」は「〜しないで」の意味が変わるので除く）
  const NEG_END = '(?=[。、！？!?\\s」』）よねのかしけとやわ]|$)';

  const KANSAI = [
    // ことば
    ['本当に|ほんとうに|ほんとに|ホントに', 'ほんまに'],
    ['本当|ほんとう|ほんと|ホント', 'ほんま'],
    ['とても|すごく|すっごく|非常に|めちゃくちゃ', 'めっちゃ'],
    ['(?:駄目|だめ|ダメ)(?:だ|です)?' + END, 'あかん'],
    ['駄目|だめ|ダメ', 'あかん'],
    ['面白い|おもしろい', 'おもろい'],
    ['ありがとう(?:ございます|ございました)?', 'おおきに'],
    ['かまわない|構わない', 'かまへん'],
    ['(?<!間)違います', 'ちゃいます'],
    ['(?<!間)違う', 'ちゃう'],
    ['てしまった', 'てもうた'],
    ['でしまった', 'でもうた'],
    ['てしまう', 'てまう'],
    ['でしまう', 'でまう'],
    ['ておいて', 'といて'],
    ['ておく', 'とく'],
    ['ている', 'てる'],
    ['でいる', 'でる'],
    ['ています', 'てます'],
    ['でいます', 'でます'],
    ['(?<=^|[。、！？!?\\sはもがをにで「])いい(?=[よねなの。！？!?]|$)', 'ええ'],
    // 否定（〜ない → 〜へん）
    ['しないで(?=ください|ね|。|、|！|$)', 'せんといて'],
    ['しない' + NEG_END, 'せえへん'],
    ['できない|出来ない', 'でけへん'],
    ['あり得ない|ありえない', 'ありえへん'],
    ['来ない', 'けえへん'],
    ['わからない|分からない|分らない|判らない', 'わからへん'],
    ['ていない', 'てへん'],
    ['でいない', 'でへん'],
    ['(?<=^|[。、！？!?\\sもはがに])いない' + NEG_END, 'おらへん'],
    ['(?<!きた|おさ|はか|しかた|しか)(?<=[かさたまらわば])ない' + NEG_END, 'へん'],
    ['(?<!さりげ|なにげ|何気|大人げ|おとなげ)(?<=[べめけせてねれえげで])ない' + NEG_END, 'へん'],
    ['ではありません|じゃありません', 'ちゃいます'],
    ['ません(?=でした|か|よ|ね|[。、！？!?\\s」』）]|$)', 'まへん'],
    // 「じゃない」など
    ['じゃないか|じゃないですか', 'やんか'],
    ['じゃないの', 'ちゃうの'],
    ['じゃない|ではない', 'ちゃう'],
    ['じゃん', 'やん'],
    // 「だ」→「や」
    [START + 'だから', 'せやから'],
    [START + 'だけど', 'せやけど'],
    [START + 'だって', 'せやかて'],
    ['そうだよ', 'せやで'],
    ['そうだね', 'せやな'],
    ['そうだ' + END, 'せや'],
    [EXPL + 'んだよ', 'んやで'],
    [EXPL + 'んだね', 'んやな'],
    [EXPL + 'んだから', 'んやから'],
    [EXPL + 'んだけど', 'んやけど'],
    [EXPL + 'んだった', 'んやった'],
    [EXPL + 'んだろう?', 'んやろ'],
    [EXPL + 'んだ' + END, 'んや'],
    ['のだ' + END, 'んや'],
    [NOUN + 'だよね', 'やんな'],
    [NOUN + 'だよ', 'やで'],
    [NOUN + 'だ[ねな]', 'やな'],
    [NOUN + 'だから', 'やから'],
    [NOUN + 'だけど', 'やけど'],
    [NOUN + 'だった', 'やった'],
    [NOUN + 'だろう?', 'やろ'],
    [NOUN + 'だって', 'やって'],
    [NOUN + 'だ' + END, 'や'],
    ['なの(?=[？?。！!]|$)', 'なん'],
  ];

  // 大阪のおばちゃんだけの言い回し
  const OBACHAN = [
    ['あなた|貴方', 'あんた'],
    ['(?<![ぁ-ん一-龯])(?:私|わたし)(?=[はがのもをにとっ])', 'うち'],
    ['飴(?!ちゃん)', 'あめちゃん'],
    ['ですよ(?=[。！!]|$)', 'でっせ'],
    ['ますよ(?=[。！!]|$)', 'まっせ'],
    ['でしょう(?=[。？?]|$)', 'でっしゃろ'],
  ];

  // 古いブラウザで使えない書き方の決まりは、そのまま飛ばす（アプリ全体を止めない）
  const compile = (list) => list.flatMap(([re, to]) => {
    try { return [[new RegExp(re, 'g'), to]]; } catch { return []; }
  });
  const kansai = compile(KANSAI);
  const obachan = compile(OBACHAN);

  function convert(text, { dialect, obachan: isObachan } = {}) {
    let out = text;
    if (isObachan) for (const [re, to] of obachan) out = out.replace(re, to);
    if (dialect === 'kansai') for (const [re, to] of kansai) out = out.replace(re, to);
    return out;
  }

  return { convert };
})();
